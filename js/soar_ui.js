/**
 * NetShield AI - SOAR UI & Report Export Controller
 */

class SOARUIController {
  constructor() {
    this.actionHistory = [];
  }

  showNotification(msg, type = "info") {
    const toast = document.createElement('div');
    toast.style.position = 'fixed';
    toast.style.top = '1.5rem';
    toast.style.right = '1.5rem';
    toast.style.padding = '0.85rem 1.5rem';
    toast.style.borderRadius = '8px';
    toast.style.background = type === 'danger' ? '#ef4444' : (type === 'success' ? '#10b981' : '#00f2fe');
    toast.style.color = '#000';
    toast.style.fontWeight = 'bold';
    toast.style.zIndex = '1000';
    toast.style.boxShadow = '0 4px 20px rgba(0,0,0,0.5)';
    toast.innerHTML = msg;

    document.body.appendChild(toast);
    setTimeout(() => toast.remove(), 3500);
  }

  executeSOARAction(actionName, target) {
    const timestamp = new Date().toLocaleTimeString();
    const entry = { action: actionName, target: target, timestamp: timestamp };
    this.actionHistory.push(entry);

    this.showNotification(`⚡ SOAR Executed: [${actionName}] on ${target}`, 'danger');

    // Update log UI if present
    const soarList = document.getElementById('soarActionList');
    if (soarList) {
      const item = document.createElement('div');
      item.style.padding = '0.5rem 0.75rem';
      item.style.borderBottom = '1px solid rgba(45,62,98,0.3)';
      item.style.fontSize = '0.8rem';
      item.innerHTML = `<span style="color:#10b981;">✓ ${timestamp}</span> - Executed <strong>${actionName}</strong> on <code>${target}</code>`;
      soarList.prepend(item);
    }
  }

  downloadIncidentReport(deviceName, deviceIp) {
    const reportText = `# 🛡️ NetShield AI Security Incident Investigation Report
Report ID: INC-2026-9412
Target Asset: ${deviceName} (${deviceIp})
Timestamp: ${new Date().toISOString()}
Risk Score: 96% | Confidence: 97% | Status: COMPROMISED

---

## 1. Executive Summary
On 2026-08-07, NetShield AI detected a CRITICAL network compromise on asset ${deviceName} (${deviceIp}). The incident involved an automated SSH Brute Force attack originated from known malicious C2 IP 185.220.101.5 (Country: Russia, Threat: LockBit Ransomware C2).

---

## 2. Explainable AI (XAI) Contributing Evidence
- 412 Failed SSH Login Attempts within 60s window
- Outbound connections to known malicious C2 IP 185.220.101.5
- Outbound payload volume burst: 2.3 GB
- High entropy DNS subdomains matching C2 heartbeat pattern

---

## 3. MITRE ATT&CK Mapping
- T1110 (Brute Force - Credential Access)
- T1071 (Application Layer Protocol C2)

---

## 4. SOAR Playbooks Executed
- ✓ Block IP: 185.220.101.5 on Perimeter Firewall
- ✓ Isolate Host: ${deviceName} moved to VLAN 999
- ✓ Process Killed: PID 4912 (sshd brute child process)

Report generated by NetShield AI Security Copilot.`;

    const blob = new Blob([reportText], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `NetShield_Incident_Report_${deviceName.replace(/\s+/g, '_')}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);

    this.showNotification("📑 Incident Report exported successfully as Markdown file!", "success");
  }
}

window.SOARUIController = SOARUIController;
